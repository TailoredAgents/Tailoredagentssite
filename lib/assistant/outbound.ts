const extended=(v:AssistantEmail)=>v.replyMode!=='new'||v.attachments.length>0||v.cc.length>0||v.bcc.length>0||v.to.includes(',');
async function emailDetails(p:Principal,input:AssistantEmail,withBytes=false){
 const sender=await requireInboxMailbox(p.context,input.mailboxId,true),to=input.to.split(', '),all=[...to,...input.cc,...input.bcc];
 if(all.length>20||new Set(all).size!==all.length)throw new AssistantError('email_recipients','Choose at most 20 distinct recipients across To, CC and BCC.');
 if(extended(input)&&process.env.ASSISTANT_COMMUNICATIONS_ENABLED==='false')throw new AssistantError('mail_setup','Chat replies and attachments are paused.',503);
 if(input.replyMode==='new'){
  if(input.threadId||input.replyToMessageId||input.threadRevision)throw new AssistantError('email_target','A new email must not include a reply target.');
 }else{
  if(!input.threadId||!input.replyToMessageId||!input.threadRevision)throw new AssistantError('email_target','Read the current email reply context first.');
  const current=await getMailReplyContext(p.context,input.mailboxId,input.threadId),recipients=input.replyMode==='reply_all'?current.replyAll:current.reply;
  if(current.messageId!==input.replyToMessageId||current.revision!==input.threadRevision||current.subject!==input.subject||JSON.stringify(recipients)!==JSON.stringify({to,cc:input.cc,bcc:input.bcc}))throw new AssistantError('email_changed','The conversation or reply recipients changed. Read the latest message and prepare a new review.',409);
 }
 if(extended(input))await getMailComposeCapabilities(p.context,input.mailboxId);
 const envelope:EmailEnvelope={to,cc:input.cc,bcc:input.bcc,replyMode:input.replyMode,threadRevision:input.threadRevision,attachments:[]};let total=0;
 if(new Set(input.attachments.map(a=>a.id)).size!==input.attachments.length)throw new AssistantError('email_attachment','Choose each attachment once.');
 for(const attachment of input.attachments){
  const file=await documentDownload(p.context,attachment.id);total+=file.bytes.length;
  if(!file.document.generated||!['pdf','docx','csv','xlsx'].includes(file.document.extension))throw new AssistantError('email_attachment','Email attachments must be data-only files generated by the assistant. Original uploads cannot be forwarded.');
  if(file.document.hash!==attachment.hash||total>5000000)throw new AssistantError('email_attachment','An attachment changed or the combined files exceed 5 MB. Prepare a new review.',409);
  envelope.attachments.push({id:attachment.id,name:file.document.name,mime:file.mime,hash:attachment.hash,bytes:file.bytes.length,...(withBytes?{content:file.bytes.toString('base64')}: {})});
 }
 return {sender,envelope};
}
export async function emailReview(p:Principal,raw:unknown){
 const input=emailSchema.parse(raw),details=await emailDetails(p,input);
 // Keep the simple new-email transport compatible with the existing Mail release.
 if(!extended(input))return {sender:details.sender,recipient:input.to,subject:input.subject,text:input.text,notice:'Sends this exact new email after your review. Provider acceptance is not proof of delivery.'};
 return {sender:details.sender,envelope:emailEnvelopeIdentity(details.envelope),subject:input.subject,text:input.text,threadId:input.threadId,replyToMessageId:input.replyToMessageId,notice:'Review the exact recipients, message and files. Acceptance is not proof of delivery. Attachments leave the private workspace when sent.'};
}
export async function executeEmail(p:Principal,raw:unknown){
 try{
  const input=emailSchema.parse(raw),details=extended(input)?await emailDetails(p,input,true):null;
  const result=await sendInboxMessage(p.context,{...input,threadId:input.threadId??undefined,replyToMessageId:input.replyToMessageId??undefined},{...(details?{emailEnvelope:details.envelope}:{}),beforeDelivery:()=>asAssistant(p,['conversations:read','mail:send'],true,async fresh=>{if(details){const current=await emailDetails(fresh,input);if(JSON.stringify(emailEnvelopeIdentity(current.envelope))!==JSON.stringify(emailEnvelopeIdentity(details.envelope)))throw new AssistantError('email_changed','The reviewed email changed.',409);}})});
  if(result.sendState!=='accepted')throw new AssistantOutcomeError(result.sendState==='rejected'?'failed':'outcome_unknown',result);return result;
 }catch(e){if(e instanceof InboxAccessError||e instanceof InboxInputError)throw new AssistantError('mail_rejected',e.message,409);throw e;}
}
export const callCustomerSchema=intentSchema.omit({mode:true});
export async function callReview(p:Principal,raw:unknown){
 const input=callCustomerSchema.parse(raw),workspace=await getVoiceWorkspace(p.context);
 const line=workspace.lines.find(l=>l.id===input.lineId);
 if(!line)throw new AssistantError('call_unavailable','This calling line is unavailable.',403);
 return {line,customerPhone:input.to,notice:'Rings your approved employee phone. Answer and press 1 to connect the customer. Standard calling charges apply.'};
}
export async function executeCall(p:Principal,raw:unknown){
 const intent=await createVoiceIntent(p.context,{...callCustomerSchema.parse(raw),mode:'phone'});
 const message=await asAssistant(p,['conversations:read','voice:send'],true,fresh=>startPhoneCall(fresh.context,{callId:intent.callId}));
 // Never return the device/intention credential to a model.
 const result={callId:intent.callId,message};
 if(message.includes('awaiting confirmation'))throw new AssistantOutcomeError('outcome_unknown',result);
 return result;
}
