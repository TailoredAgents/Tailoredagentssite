test('share images, stable QR redirects and contact downloads for all sellers',async({request},info)=>{
 for(const person of ['austin','jeffrey','devon']){
  const image=await request.get(`${path}/share-image?card=freight-${person}`);expect(image.status()).toBe(200);
  const bytes=await image.body();const size=await sharp(bytes).metadata();expect([size.width,size.height]).toEqual([1200,630]);
  await writeFile(info.outputPath(`freight-share-${person}.png`),bytes);
  const qr=await request.get(`/api/smart-cards/qr/freight-${person}?format=png`);expect(qr.status()).toBe(200);
  expect(qr.headers()['content-type']).toBe('image/png');await writeFile(info.outputPath(`freight-qr-${person}.png`),await qr.body());
  const redirect=await request.get(`/go/freight-${person}?via=qr`,{maxRedirects:0});expect(redirect.status()).toBe(307);
  const location=new URL(redirect.headers().location);expect(location.pathname).toBe(path);expect(location.searchParams.get('card')).toBe(`freight-${person}`);expect(location.searchParams.get('utm_campaign')).toBe('freight-automation');
  expect(await(await request.get(`/c/${person}/contact`)).text()).toContain(`${person}@tailoredagents.com`);
 }
});
