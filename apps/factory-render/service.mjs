const MAX_BYTES = 64_000_000;
const PRIVATE_HEADERS = { "cache-control": "no-store", "x-content-type-options": "nosniff", "content-type": "text/plain; charset=utf-8" };
class HttpError extends Error { constructor(status) { super("Website storage unavailable"); this.status = status; } }

// Keep in step with the CRM storage adapter. Keys are generated by the CRM, never
// paths supplied by preview visitors. Windows delimiters and percent escapes fail.
export function validKey(key) {
  if (typeof key !== "string" || !/^factory\/[0-9a-f-]{36}\/[0-9a-f-]{36}\/[a-zA-Z0-9_./-]+$/.test(key) || key.length > 500 || key.includes("//") || key.split("/").some(part => part === "." || part === "..")) throw new HttpError(400);
  return key;
}
function validPrefix(prefix) {
  validKey(prefix);
  if (!/^factory\/[0-9a-f-]{36}\/[0-9a-f-]{36}\/(?:[0-9a-f-]{36}\/|uploads\/[0-9a-f-]{36}\.(?:png|jpg|webp))$/.test(prefix)) throw new HttpError(400);
  return prefix;
}
function authorized(header, secret) {
  if (typeof secret !== "string" || secret.length < 32 || typeof header !== "string" || header.length > 4103) return false;
  const digest = value => createHash("sha256").update(value).digest();
  return timingSafeEqual(digest(header), digest(`Bearer ${secret}`));
}
function boundedNumber(value, fallback, ceiling) {
  if (value === null) return fallback;
  if (!/^(0|[1-9][0-9]*)$/.test(value)) throw new HttpError(400);
  const parsed = Number(value);
  if (!Number.isSafeInteger(parsed) || parsed > ceiling) throw new HttpError(400);
  return parsed;
}
function safeReply(res, status, message = "Website storage unavailable") {
  if (res.headersSent || res.destroyed) { res.destroy(); return; }
  if (status >= 400) res.setHeader("connection", "close");
  res.writeHead(status, PRIVATE_HEADERS);
  res.end(status === 204 ? undefined : message);
}

export async function createDiskStore(directory) {
  const configured = path.resolve(directory);
  await mkdir(configured, { recursive: true, mode: 0o700 });
  const rootInfo = await lstat(configured);
  if (rootInfo.isSymbolicLink() || !rootInfo.isDirectory()) throw new Error("Invalid website storage directory");
  const root = await realpath(configured);
  // A process interrupted during an upload can leave an unreferenced temporary
  // file. Only old, service-created temporary files are removed, on bounded startup.
  let scanned = 0;
  const cleanupDeadline = Date.now() + 10_000;
  async function cleanupTemporaryFiles(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (++scanned > 50_000 || Date.now() > cleanupDeadline) return;
      const filename = path.join(directory, entry.name);
      if (entry.isSymbolicLink()) continue;
      if (entry.isDirectory()) await cleanupTemporaryFiles(filename);
      else if (entry.isFile() && /^\.(upload|health)-[0-9a-f-]{36}$/.test(entry.name)) {
        const info = await lstat(filename);
        if (!info.isSymbolicLink() && info.mtimeMs < Date.now() - 60 * 60_000) await rm(filename, { force: true });
      }
    }
  }
  await cleanupTemporaryFiles(root);
  // All service mutations for the same project serialize. A delete cannot race
  // an in-flight upload or remove the upload's parent before atomic rename.
  const projectLocks = new Map();
  async function exclusive(key, work) {
    const scope = key.split("/").slice(0, 3).join("/");
    const previous = projectLocks.get(scope) || Promise.resolve();
    let unlock;
    const barrier = new Promise(resolve => { unlock = resolve; });
    const tail = previous.then(() => barrier);
    projectLocks.set(scope, tail);
    await previous;
    try { return await work(); }
    finally { unlock(); if (projectLocks.get(scope) === tail) projectLocks.delete(scope); }
  }
  async function checkedPath(key, createParents = false) {
    validKey(key);
    const segments = key.replace(/\/$/, "").split("/");
    let current = root;
    for (let index = 0; index < segments.length; index++) {
      current = path.join(current, segments[index]);
      const parent = index < segments.length - 1;
      if (parent && createParents) {
        try { await mkdir(current, { mode: 0o700 }); } catch (error) { if (error.code !== "EEXIST") throw error; }
      }
      try {
        const info = await lstat(current);
        if (info.isSymbolicLink() || (parent && !info.isDirectory())) throw new HttpError(503);
      } catch (error) { if (error.code !== "ENOENT") throw error; if (parent && !createParents) return null; }
    }
    return current;
  }
  async function read(key, maximumBytes = MAX_BYTES) {
    const filename = await checkedPath(key);
    if (!filename) return null;
    let handle;
    try {
      handle = await open(filename, constants.O_RDONLY | (constants.O_NOFOLLOW || 0));
      const info = await handle.stat();
      if (!info.isFile()) throw new HttpError(404);
      if (info.size > maximumBytes) throw new HttpError(413);
      return { handle, size: info.size };
    } catch (error) {
      await handle?.close();
      if (error.code === "ENOENT") return null;
      throw error;
    }
  }
  async function rejectSymlinks(filename) {
    const info = await lstat(filename);
    if (info.isSymbolicLink()) throw new HttpError(503);
    if (info.isDirectory()) for (const entry of await readdir(filename)) await rejectSymlinks(path.join(filename, entry));
  }
  return {
    async health() {
      const filename = path.join(root, `.health-${randomUUID()}`);
      const handle = await open(filename, "wx", 0o600);
      try { await handle.writeFile("ok"); } finally { await handle.close(); await rm(filename, { force: true }); }
    },
    read,
    async put(key, input, expectedLength) {
      validKey(key);
      return exclusive(key, async () => {
        const disk = await statfs(root);
        if (disk.bavail * disk.bsize < (expectedLength ?? MAX_BYTES) + 16_000_000) throw new HttpError(507);
        const filename = await checkedPath(key, true);
        if (key.endsWith("/")) throw new HttpError(400);
        const temporary = path.join(path.dirname(filename), `.upload-${randomUUID()}`);
        let handle;
        try {
          handle = await open(temporary, "wx", 0o600);
          let length = 0;
          for await (const chunk of input.iterator ? input.iterator({ destroyOnReturn: false }) : input) {
            length += chunk.length;
            if (length > MAX_BYTES || (expectedLength !== null && length > expectedLength)) throw new HttpError(413);
            await handle.writeFile(chunk);
          }
          if (expectedLength !== null && length !== expectedLength) throw new HttpError(400);
          await handle.sync();
          await handle.close(); handle = undefined;
          // Recheck the leaf before replacing it; never follow a symlink.
          await checkedPath(key);
          await rename(temporary, filename);
        } finally { await handle?.close(); await rm(temporary, { force: true }); }
      });
    },
    async deletePrefix(prefix) {
      validPrefix(prefix);
      return exclusive(prefix, async () => {
        const filename = await checkedPath(prefix);
        if (!filename) return;
        try {
          await rejectSymlinks(filename);
          await rm(filename, { recursive: prefix.endsWith("/"), force: true });
        } catch (error) { if (error.code !== "ENOENT") throw error; }
      });
    },
    // R2-compatible narrow adapter, consumed by the existing verified preview
    // handler. Public assets are manifest-bound and limited to 10 MiB there.
    async get(key) {
      const object = await read(key, 10_485_760);
      if (!object) return null;
      await object.handle.close();
      return { size: object.size, async arrayBuffer() {
        const fresh = await read(key, 10_485_760);
        if (!fresh) throw new HttpError(404);
        try { const bytes = await fresh.handle.readFile(); return bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength); }
        finally { await fresh.handle.close(); }
      } };
    },
  };
}

export async function createFactoryServer({ env = process.env, fetcher = fetch, maxActiveRequests = 4 } = {}) {
  env = { ...env, FACTORY_STORAGE_SECRET: env.FACTORY_STORAGE_SECRET?.trim(), FACTORY_PREVIEW_SECRET: env.FACTORY_PREVIEW_SECRET?.trim() };
  if ([env.FACTORY_STORAGE_SECRET, env.FACTORY_PREVIEW_SECRET].some(value => typeof value !== "string" || !/^[\x20-\x7e]{32,4096}$/.test(value))) throw new Error("Website service secrets are not configured");
  if (env.FACTORY_RESOLVER_URL !== "https://www.tailoredagents.com/api/integrations/factory/preview") throw new Error("Website preview resolver is not configured");
  const store = await createDiskStore(env.FACTORY_STORAGE_DIRECTORY || "/var/data/factory");
  await store.health();
  async function boundedResolverFetch(url, init) {
    const result = await fetcher(url, init);
    if (!result.ok) return result;
    if (Number(result.headers.get("content-length")) > 150_000) { await result.body?.cancel(); throw new HttpError(503); }
    const reader = result.body?.getReader();
    if (!reader) throw new HttpError(503);
    let size = 0; const chunks = [];
    try {
      for (;;) {
        const read = await reader.read(); if (read.done) break;
        size += read.value.length;
        if (size > 150_000) { await reader.cancel(); throw new HttpError(503); }
        chunks.push(read.value);
      }
    } finally { reader.releaseLock(); }
    return new Response(Buffer.concat(chunks), { status: result.status, headers: { "content-type": "application/json" } });
  }
  let active = 0;
  const server = createServer({ requestTimeout: 65_000, headersTimeout: 15_000, maxHeaderSize: 16_384 }, async (req, res) => {
    // A finite queue protects the small shared preview service from concurrent
    // private uploads and public allocations. Streams provide backpressure.
    if (active >= maxActiveRequests) { req.resume(); safeReply(res, 503); return; }
    active++;
    let timeout;
    try {
      timeout = setTimeout(() => { req.destroy(); res.destroy(); }, 60_000);
      const url = new URL(req.url || "/", "http://factory.invalid");
      if (url.pathname === "/health" && req.method === "GET") {
        await store.health(); safeReply(res, 200, "ready"); return;
      }
      if (url.pathname.startsWith("/internal/")) {
        if (!authorized(req.headers.authorization, env.FACTORY_STORAGE_SECRET)) { req.resume(); safeReply(res, 401); return; }
        if (url.pathname === "/internal/storage/object" && ["GET", "PUT"].includes(req.method)) {
          const key = validKey(url.searchParams.get("key"));
          if (url.searchParams.getAll("key").length !== 1) throw new HttpError(400);
          if (req.method === "PUT") {
            if (req.headers["content-encoding"] && req.headers["content-encoding"] !== "identity") throw new HttpError(415);
            const length = req.headers["content-length"] === undefined ? null : boundedNumber(req.headers["content-length"], null, Number.MAX_SAFE_INTEGER);
            if (length !== null && length > MAX_BYTES) throw new HttpError(413);
            await store.put(key, req, length); safeReply(res, 204); return;
          }
          const maximumBytes = boundedNumber(url.searchParams.get("maxBytes"), MAX_BYTES, MAX_BYTES);
          const object = await store.read(key, maximumBytes);
          if (!object) { safeReply(res, 404); return; }
          res.writeHead(200, { ...PRIVATE_HEADERS, "content-type": "application/octet-stream", "content-length": String(object.size) });
          try { await pipeline(createReadStream("", { fd: object.handle.fd, autoClose: false, start: 0, end: object.size ? object.size - 1 : undefined }), res); }
          finally { await object.handle.close(); }
          return;
        }
        if (url.pathname === "/internal/storage/prefix" && req.method === "DELETE") {
          if (url.searchParams.getAll("prefix").length !== 1) throw new HttpError(400);
          await store.deletePrefix(url.searchParams.get("prefix")); safeReply(res, 204); return;
        }
        safeReply(res, 404); return;
      }
      if (url.pathname.startsWith("/p/")) {
        if (!["GET", "HEAD"].includes(req.method)) { req.resume(); safeReply(res, 404); return; }
        const request = new Request(url, { method: req.method, headers: req.headers });
        const result = await serveFactoryPreview(request, { ...env, SITES: store }, boundedResolverFetch);
        res.writeHead(result.status, Object.fromEntries(result.headers));
        if (result.body) await pipeline(Readable.fromWeb(result.body), res); else res.end();
        return;
      }
      safeReply(res, 404);
    } catch (error) {
      if (!res.headersSent) res.setHeader("connection", "close");
      req.resume();
      safeReply(res, error instanceof HttpError ? error.status : 503);
    } finally { clearTimeout(timeout); active--; }
  });
  server.keepAliveTimeout = 5_000;
  server.maxRequestsPerSocket = 100;
  server.maxConnections = 64;
  return server;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const server = await createFactoryServer();
    const port = Number(process.env.PORT || 10000);
    if (!Number.isSafeInteger(port) || port < 1 || port > 65535) throw new Error("Invalid service port");
    server.listen(port, "0.0.0.0", () => process.stdout.write("Website preview service ready\n"));
    const stop = () => { server.close(() => process.exit(0)); setTimeout(() => process.exit(1), 65_000).unref(); };
    process.on("SIGTERM", stop); process.on("SIGINT", stop);
  } catch { process.stderr.write("Website preview service could not start; check disk and required configuration.\n"); process.exitCode = 1; }
}
